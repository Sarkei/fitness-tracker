export function normalizeFoodHint(hint: string): string {
  const t = hint.trim().toLowerCase();
  if (!t) return hint.trim();
  for (const [from, to] of Object.entries(FOOD_SYNONYMS_DE)) {
    if (t === from || t.startsWith(`${from} `) || t.includes(` ${from}`)) {
      return to;
    }
  }
  return hint.trim();
}
